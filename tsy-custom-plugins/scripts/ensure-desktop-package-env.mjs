/**
 * Ensure apps/desktop/.env.windows (and .env.macos) have the shared non-secret
 * enterprise packaging values every developer on this team uses.
 *
 * Upserts only; never overwrites existing secret lines (CER, PIN, COS, CSC, …).
 * Usage: node tsy-custom-plugins/scripts/ensure-desktop-package-env.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptsDir = path.dirname(fileURLToPath(import.meta.url))
const pluginsRoot = path.resolve(scriptsDir, '..')
const repoRoot = path.resolve(pluginsRoot, '..')
const desktopRoot = path.join(repoRoot, 'apps/desktop')

/** Shared local-unsigned packaging addresses (team-wide; not secrets). */
const SHARED = {
  DSH_DESKTOP_APP_ID: 'com.deepseek.harness',
  DSH_DESKTOP_AUTO_UPDATE_ENV: 'test',
  DOWNLOAD_TEST_ORIGIN: 'https://updates.example.com',
  DOWNLOAD_TEST_RELEASE_ID: '0123456789abcdef0123456789abcdef',
  DSH_DESKTOP_MANDATORY_UPDATE_TEST_ORIGIN: 'https://policy.example.com',
  DSH_DESKTOP_MANDATORY_UPDATE_PROD_ORIGIN: 'https://policy.example.com',
  DSH_DESKTOP_MANDATORY_UPDATE_CONFIG: '{"allowedAuthOrigins":["https://login.example.com"]}',
  DSH_DESKTOP_NPM_REGISTRY: 'https://registry.npmmirror.com',
  DSH_DESKTOP_TRIAL_PLUGINS_DIR: '.desktop-build/trial-plugins',
  // Absolute so packaging does not depend on cwd.
  DSH_DESKTOP_TRIAL_DEFAULTS_FILE: path.join(pluginsRoot, 'desktop-enterprise-defaults.json'),
}

const HEADER = [
  '# Auto-maintained shared enterprise packaging values (non-secret).',
  '# Generated by tsy-custom-plugins/scripts/ensure-desktop-package-env.mjs',
  '# Secrets (CER / PIN / COS / CSC / …) are never written here — add them yourself.',
  '',
].join('\n')

/**
 * Parse KEY=VALUE lines; keep first occurrence; ignore comments/blank.
 * @param {string} text
 * @returns {Map<string, string>}
 */
function parseEnv(text) {
  const map = new Map()
  for (const line of text.split(/\r?\n/)) {
    if (/^\s*(#|$)/.test(line)) continue
    const eq = line.indexOf('=')
    if (eq <= 0) continue
    const key = line.slice(0, eq).trim()
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) continue
    if (!map.has(key)) map.set(key, line.slice(eq + 1))
  }
  return map
}

/**
 * Upsert SHARED keys into one env file without dropping unknown/secret keys.
 * @param {string} envFile
 */
function ensureEnvFile(envFile) {
  const existingText = fs.existsSync(envFile) ? fs.readFileSync(envFile, 'utf8') : ''
  const existing = parseEnv(existingText)
  const next = new Map(existing)
  const changed = []
  for (const [key, value] of Object.entries(SHARED)) {
    if (next.get(key) === value) continue
    // Always force shared packaging keys to the team values (addresses/ids).
    next.set(key, value)
    changed.push(key)
  }
  if (changed.length === 0 && existingText.trim() !== '') {
    console.log(`ok ${path.relative(repoRoot, envFile)} (unchanged)`)
    return
  }

  const lines = [HEADER]
  // Shared keys first (stable order), then any leftover developer keys.
  for (const key of Object.keys(SHARED)) {
    lines.push(`${key}=${next.get(key)}`)
    next.delete(key)
  }
  const extras = [...next.keys()].sort()
  if (extras.length > 0) {
    lines.push('')
    lines.push('# Local-only keys (preserved)')
    for (const key of extras) lines.push(`${key}=${next.get(key)}`)
  }
  lines.push('')
  fs.writeFileSync(envFile, lines.join('\n'), 'utf8')
  console.log(`wrote ${path.relative(repoRoot, envFile)} (${changed.length ? `set ${changed.join(', ')}` : 'created'})`)
}

const defaultsPath = SHARED.DSH_DESKTOP_TRIAL_DEFAULTS_FILE
if (!fs.existsSync(defaultsPath)) {
  throw new Error(`ensure-desktop-package-env: missing ${defaultsPath}`)
}
const defaults = JSON.parse(fs.readFileSync(defaultsPath, 'utf8'))
if (defaults?.credentialRef !== 'T4Y_DESKTOP_ENTERPRISE_GATE') {
  throw new Error('ensure-desktop-package-env: desktop-enterprise-defaults.json must use T4Y_DESKTOP_ENTERPRISE_GATE')
}

fs.mkdirSync(desktopRoot, { recursive: true })
for (const name of ['.env.windows', '.env.macos']) {
  ensureEnvFile(path.join(desktopRoot, name))
}

console.log('enterprise packaging env ready (shared origins + trial defaults)')
